/**
 * The command line.
 *
 * `--harness stub` exists because a judgement that can only ever be exercised on a
 * machine with a harness and a model is a judgement nobody can check. `--no-hub` exists
 * because "the hub is absent" is a claim somebody has to be able to test, and the only
 * honest way to make it is to not start one. Neither can turn a failure into a pass: the
 * stub feeds the real installed plugin, and `--no-hub` fails every assertion that needed a
 * hub. There is deliberately no `--skip`, no `--tolerate` and no `--expect-failure`, since
 * each would reintroduce the green-but-empty result this script exists to make impossible.
 */
export function parseArgs(argv) {
  const args = {
    out: DEFAULT_EVIDENCE_PATH,
    keepState: false,
    help: false,
    harness: 'opencode',
    hub: true,
    stubPlan: 'block',
  }
  const list = Array.isArray(argv) ? argv : []
  for (let index = 0; index < list.length; index += 1) {
    const argument = list[index]
    if (argument === '--help' || argument === '-h') args.help = true
    else if (argument === '--keep-state') args.keepState = true
    else if (argument === '--no-hub') args.hub = false
    else if (argument === '--harness') {
      const value = list[index + 1]
      if (value === undefined || value.startsWith('--')) throw new UsageError('--harness needs an id')
      args.harness = value
      index += 1
    } else if (argument === '--stub-plan') {
      const value = list[index + 1]
      if (value === undefined || value.startsWith('--')) throw new UsageError('--stub-plan needs an id')
      args.stubPlan = value
      index += 1
    } else if (argument === '--out') {
      const value = list[index + 1]
      if (value === undefined || value.startsWith('--')) throw new UsageError('--out needs a path')
      args.out = value
      index += 1
    } else throw new UsageError(`unrecognised argument: ${argument}`)
  }
  if (args.harness !== 'opencode' && args.harness !== 'stub') {
    throw new UsageError(`--harness takes 'opencode' or 'stub', not '${args.harness}'`)
  }
  if (!STUB_PLANS.includes(args.stubPlan)) {
    throw new UsageError(`--stub-plan takes one of ${STUB_PLANS.join(', ')}, not '${args.stubPlan}'`)
  }
  return args
}

