/**
 * One line of the harness's own log, as the closed fields this run reads.
 *
 * The real shape, from `opencode run --print-logs` on 1.18.32, is a flat `key=value` run
 * of the body the plugin handed `client.app.log`:
 *
 *     timestamp=2026-09-27T11:52:30.440Z level=WARN run=00046109 \
 *       message="agent-ping reported the event and the hub refused it, so nothing was stored. \
 *       The hub's own error code is on this line." service=agent-ping stage=delivery-failed \
 *       code=hub-refused harness=opencode eventName=permission.replied sessionId=ses_f1d4a7 \
 *       status=422 hubError=unidentifiable-block
 *
 * Only a line carrying `service=agent-ping` is agent-ping's, and only ten keys of it are
 * read: the service, the level, the stage, the closed failure code, the harness, the
 * harness's own event name, its variant, the session id, the HTTP status and the hub's own
 * error token. The adapter's `DeliveryBreadcrumb` has no other field, so a field added here
 * would be a field no product line can carry.
 * The message is never read and never copied, because a message on a line that is not
 * agent-ping's can be anything the harness logged (APX-FR-01).
 *
 * A value is either a double-quoted run - spaces included, with a backslash escape - or a
 * bare run up to the next space. Anything else on the line is ignored, which is what lets
 * one reader serve both the real harness and the stub.
 */
export function parseHarnessLogLine(line) {
  if (typeof line !== 'string') return null
  if (!/(?:^|\s)service=agent-ping(?:\s|$)/.test(line)) return null
  const fields = {}
  const pattern = /([A-Za-z][A-Za-z0-9]*)=("(?:[^"\\]|\\.)*"|\S+)/g
  let match
  while ((match = pattern.exec(line)) !== null) {
    const key = match[1]
    if (fields[key] !== undefined) continue
    fields[key] = match[2].startsWith('"') ? match[2].slice(1, -1).replace(/\\(.)/g, '$1') : match[2]
  }
  if (fields['service'] !== 'agent-ping') return null
  const record = { service: fields['service'], level: fields['level'] ?? null }
  for (const key of ['stage', 'code', 'harness', 'eventName', 'variant', 'sessionId', 'status', 'hubError', 'errorCode']) {
    const value = fields[key]
    if (typeof value === 'string' && value !== '') record[key] = value
  }
  return record
}

/**
 * Whether a breadcrumb names the three things OA-FR-05 asks it to name.
 *
 * The service is the filter that got the line here at all, so the answer is about the
 * session and the event type - and a line that carries a service and a code but no session
 * is `missing-session` rather than a pass, because a breadcrumb nobody can attribute to a
 * session is exactly the swallowed event this requirement exists to prevent.
 */
export function breadcrumbVerdict(crumb) {
  if (crumb === null || crumb === undefined) return 'no-breadcrumb'
  if (crumb.service !== 'agent-ping') return 'not-this-product'
  if (typeof crumb.sessionId !== 'string' || crumb.sessionId === '' || crumb.sessionId === 'unknown') {
    return 'missing-session'
  }
  if (typeof crumb.eventName !== 'string' || crumb.eventName === '' || crumb.eventName === 'unknown') {
    return 'missing-event-name'
  }
  if (typeof crumb.harness !== 'string' || crumb.harness === '') return 'missing-harness'
  return 'service+session+event'
}

/**
 * Every agent-ping line in a block of harness output, as closed records.
 *
 * The reader of the log is this one function, and it keeps only the six fields above, so
 * a summary built from its output cannot carry a prompt, a diff or a path. A line the
 * parser cannot read at all is not an error here: a harness that printed something new
 * beside the breadcrumbs must not be able to fail this run.
 */
export function readBreadcrumbs(lines) {
  const crumbs = []
  for (const line of Array.isArray(lines) ? lines : []) {
    const crumb = parseHarnessLogLine(line)
    if (crumb !== null) crumbs.push(crumb)
  }
  return crumbs
}

/** One report line from the hub harness, or null. Nothing half-parsed is ever a reading. */
export function parseHubReportLine(line) {
  if (typeof line !== 'string' || !line.startsWith(HUB_REPORT_PREFIX)) return null
  try {
    const parsed = JSON.parse(line.slice(HUB_REPORT_PREFIX.length))
    if (typeof parsed !== 'object' || parsed === null) return null
    return parsed
  } catch {
    return null
  }
}

/** One card report line from the hub harness, or null. */
export function parseCardReportLine(line) {
  if (typeof line !== 'string' || !line.startsWith(CARD_REPORT_PREFIX)) return null
  try {
    const parsed = JSON.parse(line.slice(CARD_REPORT_PREFIX.length))
    if (typeof parsed !== 'object' || parsed === null || !Number.isInteger(parsed.seq)) return null
    return parsed
  } catch {
    return null
  }
}

/**
 * What the notification surface was asked to do between two readings.
 *
 * Cumulative counts in, a delta out, because the hub is one process and one surface for
 * the whole run: a greeting session's "no card" is only a statement about the moment it
 * ran, and a count that had been read from the start of the run would be answering a
 * different question. `byClass` is what separates the block's card from the finished
 * turn's card, so an assertion can name the one it means.
 */
export function cardDelta(before, after) {
  const at = (report, key) => (report !== null && report !== undefined && Number.isInteger(report[key]) ? report[key] : null)
  const cardsOf = (report) => (Array.isArray(report?.cards) ? report.cards : [])
  const beforeCards = cardsOf(before)
  const afterCards = cardsOf(after)
  const byClass = {}
  for (const card of afterCards.slice(beforeCards.length)) {
    const name = typeof card?.class === 'string' ? card.class : 'unknown'
    byClass[name] = (byClass[name] ?? 0) + 1
  }
  const showsBefore = at(before, 'shows')
  const showsAfter = at(after, 'shows')
  return {
    presents: (at(after, 'presents') ?? 0) - (at(before, 'presents') ?? 0),
    shows:
      showsBefore === null || showsAfter === null ? null : showsAfter - showsBefore,
    byClass,
    cards: afterCards.slice(beforeCards.length),
  }
}

/** How many cards of one class the surface was asked to present, as a comparison string. */
export function classCardCount(delta, className) {
  return String(delta?.byClass?.[className] ?? 0)
}

/**
 * The hub's published record, as a value, or null.
 *
 * Pure over the file's text so a decision about whether the hub published a live port can
 * be tested without a filesystem: `port: null` is the product's own "still starting"
 * answer, and a body this build cannot read is null rather than a guess.
 */
export function parseRuntimeRecord(text) {
  if (typeof text !== 'string' || text.trim() === '') return null
  let parsed
  try {
    parsed = JSON.parse(text)
  } catch {
    return null
  }
  if (typeof parsed !== 'object' || parsed === null) return null
  if (typeof parsed['host'] !== 'string' || !Number.isInteger(parsed['port'])) return null
  return {
    host: parsed['host'],
    port: parsed['port'],
    instanceId: typeof parsed['instanceId'] === 'string' ? parsed['instanceId'] : null,
    pid: Number.isInteger(parsed['pid']) ? parsed['pid'] : null,
    stateDir: typeof parsed['stateDir'] === 'string' ? parsed['stateDir'] : null,
  }
}

/** One assertion row, built in one place so `journey` is never forgotten. */
export const observation = (journey, name, expected, actual, measured) => ({
  journey,
  name,
  expected,
  actual,
  ...(measured === undefined ? {} : { measured }),
})

/**
 * The rows a journey owes when it never got far enough to observe anything.
 *
 * A journey that cannot produce its own rows produces these instead, so the inventory
 * cannot drift: the shortfall guard in `decide` is only meaningful because a journey that
 * dies still pays its debt.
 */
export function notObserved(journey, names, reason) {
  return names.map((name) => observation(journey, name, 'observed', `not-observed: ${reason}`))
}

