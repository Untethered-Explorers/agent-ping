/** Write the evidence file, and say whether it was written. */
function writeEvidence(outPath, evidence) {
  try {
    mkdirSync(path.dirname(path.resolve(outPath)), { recursive: true })
    writeFileSync(outPath, `${JSON.stringify(evidence, null, 2)}\n`, 'utf8')
    return { written: true, path: outPath }
  } catch (cause) {
    return { written: false, path: outPath, error: scrub(cause?.message ?? cause) }
  }
}

const emit = (summary) => {
  process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`)
}

async function main(argv) {
  let args
  try {
    args = parseArgs(argv)
  } catch (error) {
    process.stderr.write(`${error.message}\n\n${USAGE}\n`)
    return error.code ?? 2
  }
  if (args.help) {
    process.stdout.write(`${USAGE}\n`)
    return 0
  }

  const pre = preflight({ harness: args.harness })
  if (pre.dependencies.some((dependency) => dependency.present !== true)) {
    // No evidence file for an absent dependency: a report that says nothing was there is
    // indistinguishable from a report that says nothing was looked for.
    const decision = decide([], { assertionsExpected: ASSERTIONS_EXPECTED, dependencies: pre.dependencies })
    emit(
      buildSummary({
        decision,
        args,
        dependencies: pre.dependencies,
        exitCode: 3,
        evidence: {
          startedAt: nowIso(),
          finishedAt: nowIso(),
          machine: { platform: process.platform, node: process.version, repoVersion: HARNESS_PROBE_VERSION },
          harness: {
            kind: args.harness,
            version: pre.version,
            expectedLine: EXPECTED_HARNESS_LINE,
            liveEvidence: false,
            ...(args.harness === 'stub' ? { stubPlan: args.stubPlan } : {}),
          },
          pluginFile: null,
          hub: null,
          delivery: null,
          isolation: { stateDir: null, absentStateDir: null, configHome: null },
          seams: { surface: null, card: null, why: null },
          requiredProductChanges: [],
        },
      }),
    )
    return 3
  }

  // One temporary root per run, in the OS temporary area and owner-only. Everything this
  // run writes lives inside it and it is removed on the way out, on the failure path too.
  // A leftover directory from a failed run must not be able to turn the next run into a
  // false failure, and a developer's real state directory, configuration home and log must
  // be unreachable from here (APX-CON-03).
  const root = mkdtempSync(path.join(tmpdir(), 'agent-ping-opencode-verify-'))
  const ctx = {
    root,
    harness: args.harness,
    stubPlan: args.stubPlan,
    binary: pre.binary,
    version: pre.version,
    dependencies: pre.dependencies,
    stateDir: path.join(root, 'state'),
    absentStateDir: path.join(root, 'state-absent'),
    configHome: path.join(root, 'config'),
    pluginFile: null,
    pluginModules: [],
    hub: null,
    hubReport: null,
    hubRequested: false,
    hubRequestedPort: null,
    origin: null,
    stopReport: null,
  }
  for (const directory of [ctx.stateDir, ctx.absentStateDir, ctx.configHome, path.join(root, 'harness'), path.join(root, 'repos')]) {
    mkdirSync(directory, { recursive: true, mode: 0o700 })
  }
  // The harness's own configuration, in a configuration home this run created. `bash: ask`
  // is what makes a session reach a permission decision at all; nothing here configures
  // agent-ping, which is given no configuration in any of the three journeys.
  mkdirSync(path.join(ctx.configHome, 'opencode'), { recursive: true })
  writeFileSync(
    path.join(ctx.configHome, 'opencode', 'opencode.json'),
    `${JSON.stringify(
      {
        $schema: 'https://opencode.ai/config.json',
        permission: { bash: 'ask', edit: 'allow' },
      },
      null,
      2,
    )}\n`,
    'utf8',
  )
  writeFileSync(path.join(root, 'harness', 'hub-main.mjs'), hubMainSource(), 'utf8')
  writeFileSync(path.join(root, 'harness', 'stub-harness.mjs'), stubHarnessSource(), 'utf8')

  let result
  try {
    if (args.hub) {
      ctx.hubRequestedPort = PREFERRED_PORT_BASE + (process.pid % 900)
      ctx.hubRequested = true
      ctx.hub = launchHub({
        mainPath: path.join(root, 'harness', 'hub-main.mjs'),
        stateDir: ctx.stateDir,
        preferredPort: ctx.hubRequestedPort,
      })
      const deadline = Date.now() + HUB_READY_TIMEOUT_MS
      let report = null
      while (Date.now() < deadline && report === null) {
        const latest = ctx.hub.latest()
        if (latest.hub !== null) report = latest.hub
        else if (latest.failures.length > 0 || ctx.hub.child.exitCode !== null) break
        else await sleep(150)
      }
      if (report !== null) {
        ctx.hubReport = report
        ctx.origin = String(report.origin)
      } else {
        const latest = ctx.hub.latest()
        const reason =
          latest.failures.length > 0
            ? 'the hub process reported a start failure'
            : ctx.hub.child.exitCode !== null
              ? `the hub process exited with status ${String(ctx.hub.child.exitCode)}`
              : `the hub published no runtime file within ${String(HUB_READY_TIMEOUT_MS)} ms`
        ctx.hubFailure = reason
        log(`no hub: ${reason}`)
      }
    }
    result = await run(ctx)
  } catch (cause) {
    process.stderr.write(`[${SCRIPT_NAME}] the run itself failed: ${scrub(cause?.stack ?? cause)}\n`)
    emit({
      script: SCRIPT_NAME,
      verdict: 'fail',
      exitCode: 1,
      startedAt: nowIso(),
      finishedAt: nowIso(),
      assertionsRun: 0,
      assertionsExpected: ASSERTIONS_EXPECTED,
      assertions: [],
      failures: [`the run threw before any assertion could be reported: ${scrub(cause?.message ?? cause)}`],
      dependencies: pre.dependencies,
      evidence: args.out,
      evidenceWritten: false,
    })
    return 1
  } finally {
    if (ctx.hub !== null) ctx.stopReport = await ctx.hub.stop()
    // Removed on every path, including the one that threw: a leftover temporary directory
    // is a leftover SQLite log and a stale runtime file, and a verification run that
    // leaves either behind is a run that can turn the next one into a false failure.
    if (args.keepState) log(`temporary directories kept at ${root}`)
    else rmSync(root, { recursive: true, force: true })
  }

  const { decision, evidence } = result
  // The hub's own copy of the run's answer, with the process stopped and the evidence
  // complete: the stop report is part of what the run observed.
  evidence.hubStopped = ctx.stopReport ?? null
  const artifact = writeEvidence(args.out, evidence)
  const summary = buildSummary({ decision, evidence, args, dependencies: pre.dependencies, exitCode: decision.exitCode })
  summary.evidenceWritten = artifact.written
  emit(summary)
  log(`evidence ${artifact.written ? 'written to' : 'could not be written to'} ${artifact.path}`)
  for (const failure of decision.failures) log(`FAIL ${failure}`)
  return decision.exitCode
}

