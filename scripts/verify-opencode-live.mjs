/** One tool's absolute path, or null. Resolved through PATH rather than handed to spawn bare. */
export function resolveOnPath(command, environment = process.env) {
  const entries = (environment.PATH ?? '').split(path.delimiter).filter((entry) => entry !== '')
  for (const entry of entries) {
    const candidate = path.join(entry, command)
    try {
      if (existsSync(candidate)) return candidate
    } catch {
      // An unreadable PATH entry is not a reason to stop looking.
    }
  }
  return null
}

