#!/usr/bin/env node
// Prove the opencode adapter against the real harness (OA-5: OA-FR-01, OA-FR-05,
// OA-FR-09, APX-CON-03, APX-CON-10, APX-FR-01, APX-FR-02, PRD 5, PRD 16 #4).
//
//   node scripts/verify-opencode-live.mjs
//   node scripts/verify-opencode-live.mjs --out docs/reviews/opencode-live-evidence.json
//   node scripts/verify-opencode-live.mjs --harness stub
//   node scripts/verify-opencode-live.mjs --no-hub
//
// THE CLAIM, IN THREE SENTENCES, BEFORE ANY CODE
//
//   positive   A real opencode session that reaches a permission decision and then goes
//              idle makes the hub store one needs-you envelope, one resolution and
//              exactly one finished envelope, every one of them carrying the short name
//              of the directory the session ran in.
//   negative   A session that opens, greets and closes stores nothing at all, reaches the
//              notification surface as no card, and leaves the pending set exactly as it
//              was. That is the anti-noise proof, and it is the one that matters most: a
//              card for a turn that did nothing is the defect this product exists to
//              avoid (ADR-004).
//   failure    With the hub not running, the session still completes and the adapter
//              writes a breadcrumb through the harness's own logging client, naming the
//              service, the session and the event type. Nothing is stored anywhere, and
//              nothing is swallowed.
//
// WHY THE HARNESS GETS A PERMISSION CONFIGURATION OF ITS OWN
// The harness has to *reach* a permission decision for the positive path to exist, and
// in this build a `bash` call is auto-allowed unless the harness is told to ask. So this
// run writes an opencode configuration of its own - `permission: { bash: "ask" }` - into
// a TEMPORARY configuration home, and every session in it inherits it. That file
// configures the *harness*, in a directory this run created and deletes. It is not
// agent-ping configuration, agent-ping is given none anywhere in this run, and the
// positive assertion of OA-FR-01 and OA-FR-09 is precisely that: the session directory
// under test carries no agent-ping file of any kind, and one globally installed plugin
// is all the adapter needs.
//
// WHY A NON-DEFAULT PORT, AND WHY THAT IS AN ASSERTION
// The adapter reads the hub's port out of the runtime file rather than assuming one
// (OA-2). This run asks the hub for a port in a range the product never prefers, and
// then asserts that a delivery arrived on *that* port. A build that dialled
// DEFAULT_HUB_PORT would find nothing listening and every envelope assertion below would
// fail, which is the honest way to be wrong.
//
// THE OBSERVERS, AND WHICH OF THEM IS THE PRODUCT'S
//   - The hub is the product's own built `startHub`, over the real loopback socket, with
//     the real ingest pipeline, the real classifier, the real SQLite log, the real routes,
//     the real delivery policy and the real class policy. Nothing is stubbed.
//   - The plugin is the product's own installed single file, generated by the real
//     installer from the real adapter sources, loaded by the real opencode binary.
//   - The notification surface is a RECORDING host and a RECORDING presenter, supplied
//     through `DesktopBridge.surface` and `DesktopBridge.renderCard` - the two seams the
//     composition root documents for exactly this purpose (src/main/index.ts, NT-8).
//     Nothing about *which* card was presented is this script's decision: the product
//     builds the card model, the product's class policy decides whether one is presented
//     at all, and the recorder only counts what it was asked to show. Whether a real
//     window is on a real display is NT-9's script and its X server, not this one's
//     claim; what is claimed here is that the adapter put a card on the surface for the
//     block and put *no* card on it for a greeting.
//   - The instrument proves itself before it is trusted: the same surface that is silent
//     for the greeting session is the one that was shown and presented a card for the
//     permission session, and that is an assertion in its own right rather than a note.
//
// FIVE PROPERTIES THIS SCRIPT MUST NEVER LOSE
//
//   1. Absence of a dependency is never a skip. A missing `opencode` binary, a missing
//      built hub entry point, a missing durable schema, a wrong harness line and a hub
//      that will not start each exit non-zero with a remedy, and a run that could not
//      start never writes an evidence file: a report that says "nothing was there" is
//      indistinguishable from a report that says "nothing was looked for".
//   2. No path reports success when nothing ran. `ASSERTIONS_EXPECTED` is a fixed number
//      and a shortfall is a failure, because the alternative is a green run in which an
//      exception in the collection phase swallowed every journey and the exit code was
//      the only thing anybody read.
//   3. The negative path is measured, not assumed. A greeting session's silence is only
//      evidence if the session really happened, so its own exit status and output length
//      are asserted alongside the absence, and the surface is asserted to have been
//      exercised by the session before it.
//   4. Nothing leaves the machine. Every socket this script opens is 127.0.0.1, every
//      process it runs is the pinned `opencode` binary or this Node, and the only file it
//      writes outside its own temporary directory is the evidence file the caller named.
//   5. No conversation content. The summary records event ids the log itself generates,
//      class names, subtype tokens, counts, versions, attribute names, closed reason
//      tokens and the *lengths* of a harness reply. It records no prompt, no tool name,
//      no diff, no tool output, and no absolute path from the developer's machine
//      (APX-FR-01, APX-CON-12). The harness's own log lines are read for six closed
//      fields and are never copied into a report.
//
// SHAPE, PER THE LIVE-VERIFICATION DISCIPLINE
//
//   scripts/verify-opencode-live.mjs        pure parsing and judgement, exported, plus the
//                                           generated hub main, the generated stub harness
//                                           and the generated installer entry, plus a thin
//                                           shell that owns every side effect
//   tests/scripts/verify-opencode-live.test.ts
//                                           drives `decide`, every parser and every
//                                           generated source with injected values, and
//                                           spawns the real script against a stub harness
//                                           for the three properties that can only be
//                                           established by running it
//
// WHAT THIS SCRIPT DELIBERATELY DOES NOT DO
// It does not touch a file under src/. It does not change the product's configuration, and
// it does not install the plugin into the developer's real configuration home: every path
// it writes is under one temporary directory it removes on the way out, including on the
// failure path. It does not answer a permission, steer a session or send a prompt. It
// does not claim a card was legible, and it does not claim a human looked at anything.
