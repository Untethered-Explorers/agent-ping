/** The largest response this script will read. */
export const MAX_RESPONSE_BYTES = 1_048_576

/**
 * A response body as JSON, or null.
 *
 * Null for an empty body and null for a body that is not JSON, because this script's reads
 * are all JSON and neither case is a fault: a hub that answers with something else is
 * reported by the assertion that wanted the value, not by a parse error here.
 */
function readJsonBody(text) {
  if (text === '') return null
  try {
    return JSON.parse(text)
  } catch {
    return null
  }
}

/**
 * One loopback HTTP request.
 *
 * `node:http` rather than the global `fetch`, for three reasons that are all about being
 * able to state what this script does: it refuses a non-loopback host outright, which is
 * the whole of APX-CON-12 for a verification script; it bounds the response in bytes; and
 * it applies its own timeout, so a hub that stopped answering is a failed assertion with
 * a reason rather than a run that hangs.
 *
 * Never rejects. Every outcome is a resolved value, because the callers build observations
 * and a rejected promise in the middle of a journey would leave the assertion count short
 * for no stated reason.
 */
export function request(url, options = {}) {
  return new Promise((resolve) => {
    let target
    try {
      target = new URL(url)
    } catch {
      resolve({ ok: false, status: 0, body: null, error: `not a URL: ${url}` })
      return
    }
    if (!['127.0.0.1', 'localhost', '[::1]'].includes(target.hostname)) {
      resolve({
        ok: false,
        status: 0,
        body: null,
        error: `refusing a request to ${target.hostname}: this script only ever talks to the loopback hub (APX-CON-12)`,
      })
      return
    }
    const chunks = []
    let received = 0
    const outgoing = http.request(
      {
        hostname: target.hostname,
        port: target.port === '' ? 80 : Number(target.port),
        path: `${target.pathname}${target.search}`,
        method: options.method ?? 'GET',
        headers: options.headers ?? {},
      },
      (response) => {
        response.on('data', (chunk) => {
          received += chunk.length
          if (received <= MAX_RESPONSE_BYTES) chunks.push(chunk)
        })
        response.on('end', () => {
          const body = readJsonBody(Buffer.concat(chunks).toString('utf8'))
          const status = response.statusCode ?? 0
          resolve({ ok: status >= 200 && status < 300, status, body })
        })
      },
    )
    outgoing.setTimeout(options.timeoutMs ?? REQUEST_TIMEOUT_MS, () => {
      outgoing.destroy(new Error(`the request exceeded ${String(options.timeoutMs ?? REQUEST_TIMEOUT_MS)} ms`))
    })
    outgoing.on('error', (cause) => {
      resolve({ ok: false, status: 0, body: null, error: cause.message })
    })
    if (typeof options.body === 'string') outgoing.write(options.body)
    outgoing.end()
  })
}

