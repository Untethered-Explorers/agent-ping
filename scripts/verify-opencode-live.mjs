/**
 * Everything that has to exist before a single assertion can run.
 *
 * Every absent item is a failure with a remedy, and the remedies are commands. A missing
 * dependency here is not an environment this script adapts to; it is a run that would
 * otherwise produce a green summary having proven nothing.
 */
function preflight({ harness }) {
  const dependencies = []
  const add = (name, present, remedy, detail) => dependencies.push({ name, present, remedy, detail })

  add(
    DependencyStatus.BUILT_ENTRY,
    existsSync(path.join(repoRoot, BUILT_ENTRY_POINT)),
    'run `npm run build` in the repository root so dist/main/main/index.js exists; this run starts the built product rather than the sources',
    BUILT_ENTRY_POINT,
  )
  add(
    DependencyStatus.BUILT_SCHEMA,
    existsSync(path.join(repoRoot, BUILT_SCHEMA_FILE)),
    'the tsc build emits JavaScript only and does not copy src/storage/schema.sql beside it, so copy it with `cp src/storage/schema.sql dist/main/storage/schema.sql`. A hub started from the build cannot open its durable log without it; the permanent fix is a copy step in scripts/build.mjs, owned by tooling-engineer under DP-1',
    BUILT_SCHEMA_FILE,
  )
  add(
    DependencyStatus.PLUGIN_SOURCES,
    existsSync(path.join(repoRoot, PLUGIN_SOURCE_ROOT, 'opencode', 'index.ts')) &&
      existsSync(path.join(repoRoot, INSTALLER_SOURCE)),
    'the adapter sources are missing from this checkout, so the installed plugin file cannot be generated from them. Run this from a full agent-ping checkout',
    `${PLUGIN_SOURCE_ROOT}/opencode/index.ts, ${INSTALLER_SOURCE}`,
  )

  let binary = null
  let version = null
  if (harness === 'opencode') {
    binary = resolveOnPath('opencode')
    add(
      DependencyStatus.HARNESS,
      binary !== null,
      'install opencode 1.18.x so `opencode` is on PATH (`npm i -g opencode@1.18`, or the installer your platform uses), or start this run from a shell whose PATH has it',
      binary ?? 'opencode is not on PATH',
    )
    if (binary !== null) {
      version = readHarnessVersion(binary)
      const line = version === null ? null : version.split('.').slice(0, 2).join('.')
      add(
        DependencyStatus.HARNESS_LINE,
        line === EXPECTED_HARNESS_LINE,
        `this build reads opencode ${EXPECTED_HARNESS_LINE}.x event payloads, and a captured observation from a different release line cannot be re-checked against it. Install ${EXPECTED_HARNESS_LINE}.x, or point this run at that build`,
        version === null ? 'the binary reported no version' : `${binary} reported ${version}`,
      )
    }
  }

  return { dependencies, binary, version }
}

/** The harness's own version line, read from the binary rather than assumed. */
function readHarnessVersion(binary) {
  const result = spawnSync(binary, ['--version'], { encoding: 'utf8', timeout: 15_000 })
  if (result.error !== undefined || result.status !== 0) return null
  const text = String(result.stdout ?? '').trim()
  const match = /\d+\.\d+\.\d+/.exec(text)
  return match === null ? (text === '' ? null : text) : match[0]
}

