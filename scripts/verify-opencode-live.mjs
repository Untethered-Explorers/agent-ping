/**
 * The whole run, as a function of everything it needs.
 *
 * Every side effect happens here or in a helper it calls, and the judgement at the end is
 * `decide`'s. The return value is the evidence, so a test can drive the journeys and read
 * the same object the evidence file is written from.
 */
async function run(ctx) {
  const startedAt = nowIso()
  const observations = []
  const evidence = {
    script: SCRIPT_NAME,
    evidenceVersion: EVIDENCE_VERSION,
    startedAt,
    finishedAt: null,
    claim: {
      positive:
        'a real opencode session that reaches a permission decision and then goes idle makes the hub store one needs-you envelope, one resolution and exactly one finished envelope, each carrying the short name of the directory the session ran in',
      negative:
        'a session that opens, greets and closes stores nothing, reaches the notification surface as no card, and leaves the pending set unchanged',
      failure:
        'with the hub not running the session still completes and the adapter writes a breadcrumb naming the service, the session and the event type',
    },
    machine: {
      platform: process.platform,
      node: process.version,
      repoVersion: HARNESS_PROBE_VERSION,
    },
    harness: {
      kind: ctx.harness,
      binary: ctx.binary,
      version: ctx.version,
      expectedLine: EXPECTED_HARNESS_LINE,
      liveEvidence: ctx.harness === 'opencode',
      ...(ctx.harness === 'stub' ? { stubPlan: ctx.stubPlan } : {}),
      ...(ctx.harness === 'stub'
        ? {
            note:
              'a stub run drives this script against a generated stand-in that loads the same installed plugin file; it verifies the script, not the live adapter claim, and its summary says so',
          }
        : {}),
    },
    isolation: {
      root: ctx.root,
      stateDir: ctx.stateDir,
      absentStateDir: ctx.absentStateDir,
      configHome: ctx.configHome,
      stateDirOverride: 'AGENT_PING_STATE_DIR, the product own override, so a run can never touch a developer log',
      configOverride: 'XDG_CONFIG_HOME, which is where opencode 1.18.32 reads its global plugin directory from',
    },
    seams: {
      surface: 'DesktopBridge.surface, supplied as a recording host: it counts show() and hide() and decides nothing',
      card: 'DesktopBridge.renderCard, supplied as a recording presenter: it records the model the product built and decides nothing',
      why:
        'these two are the composition root own documented injection points (src/main/index.ts), and whether a card is legible on a real display is scripts/verify-notification-surface.mjs claim, not this one',
    },
    productFiles: {
      builtHubEntry: BUILT_ENTRY_POINT,
      builtSchema: BUILT_SCHEMA_FILE,
      installer: INSTALLER_SOURCE,
      inlinedModules: ctx.pluginModules,
    },
    hub: null,
    opening: {},
    journeys: {},
    breadcrumbs: {},
    delivery: null,
    requiredProductChanges: [],
  }

  const opening = await runOpening(ctx)
  observations.push(...opening.rows)
  evidence.opening = opening.recorded
  evidence.pluginFile = ctx.pluginFile
  evidence.productFiles.inlinedModules = ctx.pluginModules

  // Row 2 of the opening: the session directory, measured after the block session used it.
  const blockSessionDir = path.join(ctx.root, 'repos', JOURNEYS.block.dir)
  const perRepo = existsSync(blockSessionDir) ? perRepositoryConfiguration(blockSessionDir) : []
  const perRepoRow = observation(
    'opening',
    OPENING_ASSERTIONS[1],
    'none',
    perRepo.length === 0 ? 'none' : `found: ${perRepo.join(', ')}`,
    { sessionDirectory: blockSessionDir, entries: perRepo },
  )
  observations[1] = perRepoRow
  evidence.opening.sessionDirectory = { path: blockSessionDir, agentPingEntries: perRepo }

  if (ctx.hub !== null) {
    evidence.hub = {
      origin: ctx.origin,
      port: ctx.hubReport?.port ?? null,
      preferredPort: ctx.hubReport?.preferredPort ?? null,
      instanceId: ctx.hubReport?.instanceId ?? null,
      notifier: ctx.hubReport?.notifier ?? null,
      surfaceMounted: ctx.hubReport?.surfaceMounted ?? null,
      stopped: ctx.stopReport,
    }
  }

  const block = await runBlockJourney(ctx)
  observations.push(...block.rows)
  evidence.journeys['permission-then-idle'] = block.recorded
  evidence.breadcrumbs['permission-then-idle'] = block.recorded.breadcrumbs ?? []

  const greeting = await runGreetingJourney(ctx, block.recorded.cards ?? null)
  observations.push(...greeting.rows)
  evidence.journeys['open-greet-close'] = greeting.recorded
  evidence.breadcrumbs['open-greet-close'] = greeting.recorded.breadcrumbs ?? []

  const absent = await runAbsentHubJourney(ctx)
  observations.push(...absent.rows)
  evidence.journeys['hub-absent'] = absent.recorded
  evidence.breadcrumbs['hub-absent'] = absent.recorded.breadcrumbs ?? []

  if (ctx.origin !== null) {
    const health = await readHealth(ctx.origin)
    evidence.delivery = health.delivery
  }

  const decision = decide(observations, {
    assertionsExpected: ASSERTIONS_EXPECTED,
    dependencies: ctx.dependencies,
  })
  evidence.finishedAt = nowIso()
  evidence.assertions = decision.assertions
  evidence.assertionsRun = decision.assertionsRun
  evidence.assertionsExpected = decision.assertionsExpected
  evidence.verdict = decision.verdict
  evidence.failures = decision.failures
  evidence.requiredProductChanges = requiredProductChanges(observations)
  evidence.hubDiagnostics = ctx.hub === null ? null : ctx.hub.diagnostics.slice(-40).map(scrub)

  return { decision, evidence, observations }
}

/**
 * The summary, as the one machine-readable object on stdout.
 *
 * Everything a later reader needs to re-check the run without re-running it: the harness
 * and its version, the versions of the product and the runtime, the timestamps, every
 * assertion by name with its expected and observed value, and the failures. No progress,
 * no child output, no prompt, no tool name and no path from this machine outside the
 * temporary root the caller asked to keep.
 */
export function buildSummary({ decision, evidence, args, dependencies, exitCode }) {
  return {
    script: SCRIPT_NAME,
    verdict: decision.verdict,
    exitCode,
    startedAt: evidence.startedAt,
    finishedAt: evidence.finishedAt,
    harness: {
      kind: evidence.harness.kind,
      version: evidence.harness.version,
      expectedLine: evidence.harness.expectedLine,
      liveEvidence: evidence.harness.liveEvidence,
      ...(evidence.harness.stubPlan === undefined ? {} : { stubPlan: evidence.harness.stubPlan }),
      ...(evidence.harness.note === undefined ? {} : { note: evidence.harness.note }),
    },
    product: {
      version: evidence.machine.repoVersion,
      installedPlugin: evidence.pluginFile,
      hubOrigin: evidence.hub?.origin ?? null,
      hubPort: evidence.hub?.port ?? null,
      preferredPort: evidence.hub?.preferredPort ?? null,
      notifier: evidence.hub?.notifier ?? null,
      delivery: evidence.delivery,
    },
    machine: evidence.machine,
    isolation: {
      stateDir: evidence.isolation.stateDir,
      absentStateDir: evidence.isolation.absentStateDir,
      configHome: evidence.isolation.configHome,
      stateDirOverride: evidence.isolation.stateDirOverride,
      configOverride: evidence.isolation.configOverride,
    },
    seams: evidence.seams,
    assertionsRun: decision.assertionsRun,
    assertionsExpected: decision.assertionsExpected,
    assertions: decision.assertions,
    failures: decision.failures,
    dependencies,
    requiredProductChanges: evidence.requiredProductChanges,
    evidence: args.out,
    why:
      decision.verdict === 'pass'
        ? 'every assertion ran and matched, on a real harness and a real hub'
        : `the run exercised ${String(decision.assertionsRun)} of ${String(decision.assertionsExpected)} assertions and ${String(decision.failures.length)} of them did not hold. The reasons are in failures and requiredProductChanges, and none of them was worked around`,
  }
}

