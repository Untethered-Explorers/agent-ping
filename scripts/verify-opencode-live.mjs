/**
 * The opening: one global file, no per-repository setup, and a hub on a port this run chose.
 *
 * The port is chosen outside the product's preferred range on purpose. The adapter reads
 * the port out of the runtime file rather than assuming one (OA-2), so a run whose bound
 * port is not the product's default is a run in which a delivery could only have arrived
 * by reading the file. The assertion that follows it in the block journey is the one that
 * depends on this.
 */
async function runOpening(ctx) {
  const rows = []
  const recorded = {}

  const install = await runInstaller({
    entryPath: path.join(ctx.root, 'harness', 'installer.mjs'),
    stateDir: ctx.stateDir,
    configHome: ctx.configHome,
  })
  recorded.installProcess = { status: install.status, spawnError: install.spawnError }
  const installReports = install.reports
    .filter((line) => line.startsWith(INSTALL_REPORT_PREFIX))
    .map((line) => {
      try {
        return JSON.parse(line.slice(INSTALL_REPORT_PREFIX.length))
      } catch {
        return null
      }
    })
    .filter((value) => value !== null)
  const installResult = installReports.length === 0 ? null : installReports[installReports.length - 1]
  // The stub harness loads the installed file, so it is the same file the real opencode
  // would load. Nothing else in the run may substitute for it.
  if (installResult !== null) {
    ctx.pluginFile = String(installResult.pluginFile ?? '')
    ctx.pluginModules = Array.isArray(installResult.modules) ? installResult.modules : []
  }
  recorded.install = installResult === null ? null : {
    outcome: installResult.outcome,
    code: installResult.code ?? null,
    message: scrub(installResult.message ?? ''),
    pluginFile: path.basename(String(installResult.pluginFile ?? '')),
    metadataFile: path.basename(String(installResult.metadataFile ?? '')),
    version: installResult.version ?? null,
    modules: Array.isArray(installResult.modules) ? installResult.modules : [],
    verified: installResult.observed ?? null,
  }

  // Row 1: exactly one file, and only the two the product's installer writes.
  const pluginDir = installResult === null ? null : String(installResult.pluginDir ?? '')
  const listing = pluginDir === null ? [] : listTree(pluginDir)
  const expectedListing = [METADATA_FILE_NAME, PLUGIN_FILE_NAME].sort()
  const installedCleanly =
    installResult !== null &&
    ['installed', 'reinstalled', 'unchanged'].includes(installResult.outcome) &&
    JSON.stringify(listing) === JSON.stringify(expectedListing)
  rows.push(
    observation(
      'opening',
      OPENING_ASSERTIONS[0],
      'one-file-installed',
      installedCleanly
        ? 'one-file-installed'
        : installResult === null
          ? `no-answer: ${install.spawnError ?? 'the installer child wrote no result'}`
          : `${String(installResult.outcome)}: [${listing.join(', ')}]`,
      { listing, expectedListing, outcome: installResult?.outcome ?? null },
    ),
  )

  // Row 2 is about the session directory, so it is measured after the block session has
  // used it. It is reserved here and filled in by `run`, which is why it is a placeholder
  // row rather than a separate journey: one assertion, one name, one place it is decided.
  rows.push(observation('opening', OPENING_ASSERTIONS[1], 'none', 'not-yet-measured'))

  // Row 3: the product's own runtime file, read as text and parsed by the pure reader.
  const runtimeFile = path.join(ctx.stateDir, RUNTIME_FILE_NAME)
  const runtimeText = existsSync(runtimeFile) ? readFileSync(runtimeFile, 'utf8') : ''
  const runtime = parseRuntimeRecord(runtimeText)
  const publishedPort = runtime === null ? null : runtime.port
  const choseItsOwnPort =
    runtime !== null &&
    ctx.hubRequested === true &&
    publishedPort === ctx.hubReport?.port &&
    publishedPort !== DEFAULT_HUB_PORT
  recorded.runtime = runtime
  rows.push(
    observation(
      'opening',
      OPENING_ASSERTIONS[2],
      'published-the-chosen-port',
      choseItsOwnPort
        ? 'published-the-chosen-port'
        : runtime === null
          ? 'not-published: the hub published no readable runtime file'
          : runtime.port === DEFAULT_HUB_PORT
            ? `published-the-products-default-port: ${String(runtime.port)}`
            : `published-a-port-this-run-did-not-ask-for: ${String(runtime.port)}`,
      { host: runtime?.host ?? null, port: runtime?.port ?? null, requested: ctx.hubRequestedPort },
    ),
  )

  return { rows, recorded }
}

/**
 * The positive path: a session that reaches a permission decision and then goes idle.
 *
 * Every reading is the hub's own - what it stored, what it considers pending, what its
 * delivery policy recorded - rather than what the harness said it sent. The harness's own
 * log is read for exactly one thing: the hub's *answer* to a delivery, which is how a
 * refused resolution is told apart from one that never arrived.
 */
async function runBlockJourney(ctx) {
  const journey = JOURNEYS.block.journey
  if (ctx.origin === null) {
    return { rows: notObserved(journey, BLOCK_ASSERTIONS, 'no hub is serving on this run'), recorded: {} }
  }
  const before = {
    events: await readEvents(ctx.origin),
    card: ctx.hub.cardReports().at(-1) ?? null,
  }
  const session = await runSession({
    ctx,
    which: 'block',
    prompt: BLOCK_PROMPT,
    plan: ctx.harness === 'stub' ? ctx.stubPlan : 'block',
  })
  const crumbs = sessionBreadcrumbs(session.result)

  // Wait for the hub to go quiet, then read it. The wait is for quiescence rather than for
  // any one of the things this journey asserts, because waiting for the expected envelope
  // would make a missing envelope a timeout instead of a reading.
  const quiet = await quiesce(ctx)
  const summary =
    quiet.sessions.find((entry) => entry.repoShortName === session.journey.dir) ??
    quiet.sessions.find((entry) => entry.sessionId === session.identifiers.sessionId) ??
    null
  const events = summary === null ? [] : quiet.events.filter((event) => event.sessionId === summary.sessionId)
  const after = {
    events: quiet.events,
    pending: quiet.pending,
    card: ctx.hub.cardReports().length === 0 ? null : ctx.hub.cardReports().at(-1),
  }
  const health = await readHealth(ctx.origin)
  const cards = cardDelta(before.card, after.card)
  const rows = []

  // Row 1 of this journey: a delivery arrived on a port the product does not prefer.
  const deliveredOnPublishedPort =
    ctx.hubReport !== null &&
    ctx.hubReport.port !== DEFAULT_HUB_PORT &&
    ctx.origin.endsWith(`:${String(ctx.hubReport.port)}`) &&
    (health.delivery?.attempted ?? 0) >= 1 &&
    after.events.length > before.events.length
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[0],
      'delivered-to-the-published-port',
      deliveredOnPublishedPort
        ? 'delivered-to-the-published-port'
        : health.delivery?.attempted === 0
          ? 'the hub recorded no delivery attempt at all'
          : after.events.length === before.events.length
            ? 'no event reached the hub'
            : `the hub answered on ${ctx.origin}, which is not the port this run asked it to take`,
      {
        hubPort: ctx.hubReport?.port ?? null,
        preferredPort: ctx.hubReport?.preferredPort ?? null,
        productsPreferredPort: DEFAULT_HUB_PORT,
        delivery: health.delivery,
      },
    ),
  )

  // Row 2: exactly one needs-you envelope for this session.
  const blocks = events.filter((event) => event.class === 'needs-you')
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[1],
      '1',
      String(blocks.length),
      { rawEventTypes: blocks.map((event) => event.rawEventType) },
    ),
  )

  const block = blocks[0] ?? null

  // Row 3: the block's own row identity, read from the pending set - the badge's own
  // source of truth - and matched to THIS session's block by row key rather than by class,
  // so a second block from an earlier journey cannot be read as this one's name.
  const pendingBlock =
    block === null ? null : (after.pending.items.find((item) => item.eventId === block.eventId) ?? null)
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[2],
      JOURNEYS.block.dir,
      block === null
        ? 'no-block-row'
        : pendingBlock === null
          ? 'the-block-row-is-not-in-the-pending-set'
          : (pendingBlock.repoShortName ?? 'no-short-name'),
      { pendingCount: after.pending.items.length },
    ),
  )

  // Row 4: the harness reported a resolution and the hub cleared the block. The hub's own
  // answer to the resolution signal is recorded beside it, because a block that stayed
  // pending and a resolution that was refused are different faults and only one of them
  // is the adapter's.
  const resolutionAnswer = deliveryFailures(crumbs).find((crumb) => crumb.eventName === 'permission.replied') ?? null
  const resolutionState = block === null ? null : block.resolutionState
  const stillPending =
    block === null ? false : after.pending.items.some((item) => item.eventId === block.eventId)
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[3],
      'cleared',
      block === null
        ? 'no-block-row'
        : stillPending
          ? 'still-pending'
          : resolutionState === 'resolved'
            ? 'cleared'
            : `not-cleared: ${String(resolutionState)}`,
      {
        resolutionState,
        stillInPendingSet: stillPending,
        hubAnswer: resolutionAnswer === null
          ? null
          : { code: resolutionAnswer.code ?? null, status: resolutionAnswer.status ?? null, hubError: resolutionAnswer.hubError ?? null },
      },
    ),
  )

  // Row 5: exactly one finished envelope for this session.
  const finished = events.filter((event) => event.class === 'finished')
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[4],
      '1',
      String(finished.length),
      { rawEventTypes: finished.map((event) => event.rawEventType) },
    ),
  )

  // Row 6: the finished envelope's own session identity, and the work signal the hub
  // recorded for that turn - the fact that distinguishes a worked turn from a greeting.
  // A row whose subject does not exist cannot report an identity, so an absent finished
  // envelope answers `no-finished-envelope` rather than naming the session anyway.
  rows.push(
    observation(
      journey,
      BLOCK_ASSERTIONS[5],
      JOURNEYS.block.dir,
      finished.length === 0
        ? 'no-finished-envelope'
        : summary === null
          ? 'no-session-row'
          : (summary.repoShortName ?? 'no-short-name'),
      {
        sessionId: summary?.sessionId ?? null,
        workSignal: summary?.workSignal ?? null,
        state: summary?.state ?? null,
        // The block session's own breadcrumbs, in the compact form: a reader comparing the
        // two journeys' logs wants the codes and the event names, and nothing else.
        breadcrumbs: crumbs.map((crumb) => ({
          level: crumb.level,
          code: crumb.code ?? null,
          eventName: crumb.eventName ?? null,
        })),
      },
    ),
  )

  return {
    rows,
    recorded: {
      sessionProcess: sessionProcessFacts(session.result),
      session: summary,
      events: events.map((event) => ({
        class: event.class,
        rawEventType: event.rawEventType,
        resolutionState: event.resolutionState,
      })),
      breadcrumbs: crumbs.map((crumb) => ({
        level: crumb.level,
        stage: crumb.stage ?? null,
        code: crumb.code ?? null,
        eventName: crumb.eventName ?? null,
        status: crumb.status ?? null,
        hubError: crumb.hubError ?? null,
      })),
      cards,
      delivery: health.delivery,
      hubWentQuiet: quiet.stable,
    },
  }
}

/**
 * The negative path: a session that opens, greets and closes.
 *
 * This is the anti-noise proof, so it is measured rather than assumed. Three things make
 * it a measurement: the session's own process is asserted to have run to completion, the
 * hub's whole event history is compared across it rather than searched for a row, and the
 * surface that stayed silent is asserted to have been shown a card moments earlier.
 */
async function runGreetingJourney(ctx, control) {
  const journey = JOURNEYS.greeting.journey
  if (ctx.origin === null) {
    return {
      rows: notObserved(journey, GREETING_ASSERTIONS, 'no hub is serving on this run, so there is no instrument to measure silence with'),
      recorded: {},
    }
  }
  const before = {
    events: await readEvents(ctx.origin),
    pending: await readPending(ctx.origin),
    card: ctx.hub.cardReports().at(-1) ?? null,
  }
  const session = await runSession({ ctx, which: 'greeting', prompt: GREETING_PROMPT, plan: 'greeting' })
  // The turn has to have ended before the hub can be said to have nothing from it, so the
  // wait is for the hub to go quiet rather than for a fixed number of milliseconds.
  const quiet = await quiesce(ctx)
  const after = {
    events: quiet.events,
    pending: quiet.pending,
    card: ctx.hub.cardReports().at(-1) ?? null,
  }
  const cards = cardDelta(before.card, after.card)
  const rows = []
  const completed = sessionVerdict(session.result)

  rows.push(
    observation(journey, GREETING_ASSERTIONS[0], 'completed', completed, sessionProcessFacts(session.result)),
  )
  rows.push(
    observation(
      journey,
      GREETING_ASSERTIONS[1],
      '0',
      String(classCountDelta(before.events, after.events, 'finished')),
      { eventsBefore: before.events.length, eventsAfter: after.events.length },
    ),
  )
  rows.push(
    observation(
      journey,
      GREETING_ASSERTIONS[2],
      '0',
      String(after.events.length - before.events.length),
      {
        eventsBefore: before.events.length,
        eventsAfter: after.events.length,
        pendingBefore: before.pending.items.length,
        pendingAfter: after.pending.items.length,
      },
    ),
  )
  rows.push(
    observation(
      journey,
      GREETING_ASSERTIONS[3],
      '0',
      String(cards.presents),
      { shows: cards.shows, byClass: cards.byClass },
    ),
  )
  rows.push(
    observation(
      journey,
      GREETING_ASSERTIONS[4],
      'shown-and-presented',
      control === null
        ? 'not-observed: the permission session presented no card to compare against'
        : control.presents >= 1
          ? 'shown-and-presented'
          : 'no-card-was-ever-presented',
      { control },
    ),
  )

  return {
    rows,
    recorded: {
      sessionProcess: sessionProcessFacts(session.result),
      eventsDelta: after.events.length - before.events.length,
      pendingDelta: after.pending.items.length - before.pending.items.length,
      // A session row for this repository would mean the turn was worth reporting at all,
      // and its work signal is the fact that says whether the turn did anything. Null is
      // the expected reading for a greeting, and it is recorded rather than assumed.
      sessionRow:
        quiet.sessions.find((entry) => entry.repoShortName === JOURNEYS.greeting.dir) ?? null,
      cards,
      hubWentQuiet: quiet.stable,
      breadcrumbs: sessionBreadcrumbs(session.result).map((crumb) => ({
        level: crumb.level,
        stage: crumb.stage ?? null,
        code: crumb.code ?? null,
        eventName: crumb.eventName ?? null,
      })),
    },
  }
}

/**
 * The failure path: the same session with no hub running at all.
 *
 * Its own state directory, which is empty and stays empty: no runtime file, so the
 * adapter's endpoint reader answers "no hub" before a socket is opened. What is asserted
 * is the developer's two outcomes at once - the session was unaffected, and the reason is
 * visible in the harness's own log rather than swallowed - and that nothing was stored
 * anywhere, which is what "not swallowed" must not turn into.
 */
async function runAbsentHubJourney(ctx) {
  const journey = JOURNEYS.absent.journey
  const before = listTree(ctx.absentStateDir)
  const session = await runSession({ ctx, which: 'absent', prompt: BLOCK_PROMPT, plan: 'block' })
  const crumbs = sessionBreadcrumbs(session.result)
  const failures = deliveryFailures(crumbs)
  const after = listTree(ctx.absentStateDir)
  const rows = []

  rows.push(
    observation(journey, ABSENT_HUB_ASSERTIONS[0], 'completed', sessionVerdict(session.result), sessionProcessFacts(session.result)),
  )
  rows.push(
    observation(
      journey,
      ABSENT_HUB_ASSERTIONS[1],
      'service+session+event',
      breadcrumbVerdict(failures[0] ?? null),
      { breadcrumbs: crumbs.length, deliveryFailures: failures.length },
    ),
  )
  rows.push(
    observation(
      journey,
      ABSENT_HUB_ASSERTIONS[2],
      'hub-not-running',
      failures.length === 0
        ? 'no-delivery-failed-breadcrumb'
        : (failures[0].code ?? 'no-code'),
      { codes: failures.map((crumb) => crumb.code ?? null) },
    ),
  )
  const stored = after.filter((name) => name.startsWith(DATABASE_FILE_NAME))
  rows.push(
    observation(
      journey,
      ABSENT_HUB_ASSERTIONS[3],
      'nothing-stored',
      stored.length === 0 ? 'nothing-stored' : `stored: ${stored.join(', ')}`,
      { stateDirBefore: before, stateDirAfter: after },
    ),
  )

  return {
    rows,
    recorded: {
      sessionProcess: sessionProcessFacts(session.result),
      breadcrumbs: crumbs.map((crumb) => ({
        level: crumb.level,
        stage: crumb.stage ?? null,
        code: crumb.code ?? null,
        harness: crumb.harness ?? null,
        eventName: crumb.eventName ?? null,
        sessionId: crumb.sessionId ?? null,
      })),
      stateDirContents: after,
    },
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// What this run found, as recorded requirements rather than applied changes
// ─────────────────────────────────────────────────────────────────────────────

/**
 * The product changes this run's observations point at.
 *
 * A verification run that fixed what it found would be measuring a different product than
 * the one a developer has, and the evidence would be a lie about a build that was never
 * shipped. So a finding is recorded here - with the observation it came from, the owner it
 * belongs to and the sentence that says what has to change - and nothing under src/ is
 * touched. An empty list is a claim too: it says this run found nothing that needs a
 * product change, and a reader can check that against the assertions.
 */
export function requiredProductChanges(observations) {
  const changes = []
  const byName = new Map((Array.isArray(observations) ? observations : []).map((row) => [row.name, row]))
  const blockResolution = byName.get(BLOCK_ASSERTIONS[3])
  const hubAnswer = blockResolution?.measured?.hubAnswer ?? null

  if (blockResolution !== undefined && blockResolution.actual !== 'cleared' && hubAnswer?.code === 'hub-refused') {
    changes.push({
      id: 'opencode-permission-replied-block-identity',
      owner: 'connector-engineer (OA-1)',
      references: ['OA-FR-05', 'EL-FR-08', 'ADR-004'],
      observation: BLOCK_ASSERTIONS[3],
      observed: { actual: blockResolution.actual, hubAnswer },
      finding:
        'a real opencode 1.18.32 session delivered its permission reply as ' +
        "properties { sessionID, requestID, reply }, and the adapter's block-identity reader " +
        'reads properties.permissionID, so the resolution signal carried no block identifier ' +
        `and the hub refused it rather than guessing at one: ${String(hubAnswer.status ?? 'no status')} ` +
        `${String(hubAnswer.hubError ?? 'no error token')}.`,
      requiredChange:
        'src/plugin/opencode/translate.ts: the block-identity reader must also read requestID on a ' +
        'permission.replied payload, and its evidence field must name the payload the real harness sends.',
      why:
        'a block the developer answered stays pending forever, which is the exact failure this ' +
        'product exists to prevent. The refusal is loud - it becomes a breadcrumb - so nothing is ' +
        'swallowed, but the badge still never clears.',
    })
  }
  return changes
}

