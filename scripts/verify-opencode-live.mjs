/**
 * Wait until the hub stops changing.
 *
 * A journey's claim is about what reached the hub, and both the arrival of an envelope and
 * the clearing of a block are events with a delay in them. Waiting for the specific thing
 * the journey wants would assume the answer - a run that waited for a finished envelope
 * would time out on a run where the adapter reported none, which is a different reading
 * than the one that decides the assertion. So every journey waits for *quiescence*: two
 * consecutive identical readings of the hub's events, its pending set and its sessions.
 * `stable` is reported so a reader can tell a quiet hub from a busy one.
 */
async function quiesce(ctx, boundMs = SETTLE_TIMEOUT_MS) {
  const read = async () => {
    if (ctx.origin === null) return { events: [], pending: { ok: false, items: [] }, sessions: [], stable: false }
    const [events, pending, sessions] = await Promise.all([
      readEvents(ctx.origin),
      readPending(ctx.origin),
      readSessions(ctx.origin),
    ])
    return { events, pending, sessions, stable: false }
  }
  const deadline = Date.now() + boundMs
  let previous = await read()
  while (Date.now() < deadline) {
    await sleep(200)
    const current = await read()
    if (
      JSON.stringify(current.events) === JSON.stringify(previous.events) &&
      JSON.stringify(current.pending) === JSON.stringify(previous.pending) &&
      JSON.stringify(current.sessions) === JSON.stringify(previous.sessions)
    ) {
      return { ...current, stable: true }
    }
    previous = current
  }
  return { ...previous, stable: false }
}

/** The journeys' own names, and the repository short name each one is identified by. */
const JOURNEYS = Object.freeze({
  block: { dir: 'oa5-block-repo', journey: 'permission-then-idle' },
  greeting: { dir: 'oa5-greet-repo', journey: 'open-greet-close' },
  absent: { dir: 'oa5-absent-repo', journey: 'hub-absent' },
})

/** The prompt the positive path needs: one that makes the harness reach a permission decision. */
const BLOCK_PROMPT =
  'Run the shell command: echo oa5-permission-decision'
/** The prompt the negative path needs: a greeting, with no work of any kind in the turn. */
const GREETING_PROMPT =
  'Reply with the single word PONG. Do not call any tool, do not run any command and do not edit any file.'

/**
 * One session's identifiers.
 *
 * The directory is this run's own, and the directory's basename is the repository short
 * name the hub must derive from it - which is the identity half of the claim. The other
 * identifiers exist only for a stub plan, so that two journeys in one run cannot collide
 * on a dedupe key and a short plan can be asked for without inventing a new session.
 */
function identifiersFor(root, repoShortName, token) {
  const suffix = Buffer.from(`${repoShortName}:${token}`).toString('hex').slice(0, 12)
  return {
    directory: path.join(root, 'repos', repoShortName),
    sessionId: `ses_oa5_${suffix}`,
    permissionId: `per_oa5_${suffix}`,
    callId: `call_oa5_${suffix}`,
    messageId: `msg_oa5_${suffix}`,
    token,
  }
}

/**
 * One journey's session, through whichever harness this run was given.
 *
 * One function rather than two journeys per harness, so the observations a journey builds
 * are literally the same code in both modes and a stub run cannot pass by taking a
 * different path through the script. What differs is only the process: the real binary, or
 * the generated stand-in that loads the same installed plugin file.
 */
async function runSession({ ctx, which, prompt, plan }) {
  const journey = JOURNEYS[which]
  const identifiers = identifiersFor(ctx.root, journey.dir, which)
  mkdirSync(identifiers.directory, { recursive: true, mode: 0o700 })
  const stateDir = which === 'absent' ? ctx.absentStateDir : ctx.stateDir
  if (ctx.harness === 'stub') {
    const planPath = path.join(ctx.root, 'harness', `plan-${which}.json`)
    writeFileSync(planPath, JSON.stringify(stubPlanFor(plan, identifiers), null, 2))
    const result = await runStubSession({
      entryPath: path.join(ctx.root, 'harness', 'stub-harness.mjs'),
      pluginFile: ctx.pluginFile,
      planPath,
      directory: identifiers.directory,
      stateDir,
      timeoutMs: SESSION_TIMEOUT_MS,
    })
    return { identifiers, journey, result, stateDir }
  }
  const result = await runOpencodeSession({
    binary: ctx.binary,
    directory: identifiers.directory,
    prompt,
    configHome: ctx.configHome,
    stateDir,
    timeoutMs: SESSION_TIMEOUT_MS,
  })
  return { identifiers, journey, result, stateDir }
}

/**
 * What a session's own process reported, as the two words the precondition compares.
 *
 * Three facts make "the session really happened" true, and the reply is deliberately not
 * one of them: an `opencode run` whose turn ends in a rejected permission decision can
 * print nothing on stdout and still exit zero, which two observed runs of this script
 * showed. So the reading is the exit status, the bound, and the harness's own log - a
 * session that logged nothing produced no session for this run to have measured, and
 * saying `completed` for it would make a journey's silence mean nothing.
 */
function sessionVerdict(result) {
  if (result.spawnError !== null) return `could-not-start: ${result.spawnError}`
  if (result.timedOut) return `did-not-finish: over ${String(SESSION_TIMEOUT_MS)} ms`
  if (result.status !== 0) return `exited-${String(result.status)}`
  if (!Array.isArray(result.logLines) || result.logLines.length === 0) return 'no-harness-output'
  return 'completed'
}

/** The two corroborating facts a `completed` reading is reported beside. */
function sessionProcessFacts(result) {
  return {
    exitStatus: result.status,
    timedOut: result.timedOut,
    spawnError: result.spawnError,
    replyLength: result.replyLength,
    harnessLogLines: Array.isArray(result.logLines) ? result.logLines.length : 0,
  }
}

/**
 * The agent-ping lines one session's own log holds.
 *
 * Only the ten closed fields the parser reads, and only from that session's own output. A
 * breadcrumb another session wrote is a different session's evidence, and mixing them
 * would let one journey's failure be reported as another's success.
 */
function sessionBreadcrumbs(result) {
  return readBreadcrumbs(result.logLines ?? [])
}

/** The delivery-failed breadcrumbs, which is the only stage this run reads for outcomes. */
function deliveryFailures(crumbs) {
  return crumbs.filter((crumb) => crumb.stage === 'delivery-failed')
}

/** How many rows of one class a hub's whole event history grew between two readings. */
function classCountDelta(before, after, className) {
  const count = (list, name) => (Array.isArray(list) ? list.filter((event) => event.class === name).length : 0)
  return count(after, className) - count(before, className)
}

/** Everything under a directory, as relative names, bounded so a big tree cannot fill a report. */
function listTree(root, limit = 50) {
  const found = []
  const walk = (dir, prefix) => {
    if (found.length >= limit) return
    let entries
    try {
      entries = readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      if (found.length >= limit) return
      const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`
      if (entry.isDirectory()) walk(path.join(dir, entry.name), relative)
      else found.push(relative)
    }
  }
  walk(root, '')
  return found.sort()
}

/**
 * Whether a session directory carries per-repository agent-ping configuration.
 *
 * The claim is that a developer has nothing to set up per repository (OA-FR-01, OA-FR-09),
 * so the reading is a list of every file the session directory holds after the session has
 * run - not a search for one filename. A `.opencode` directory, a project plugin, an
 * `opencode.json` and the plugin file itself are all in scope, because every one of them
 * would be a way for this session to have been configured and the other two to have been
 * invisible.
 */
function perRepositoryConfiguration(directory) {
  const suspicious = /(^|\/)(agent-ping[^/]*|opencode\.jsonc?|\.opencode)(\/|$)/i
  return listTree(directory).filter((relative) => suspicious.test(relative))
}

